import matplotlib.pyplot as plt
import numpy as np
import torch
from torch import nn
from torch_geometric.utils import add_self_loops, degree, to_undirected

class MyGCNConv(nn.Module):
    def __init__(self, in_dim, out_dim):
        super().__init__()
        self.lin = nn.Linear(in_dim, out_dim, bias=False)

    def forward(self, x: torch.Tensor, edge_index: torch.Tensor):
        edge_index, _ = add_self_loops(edge_index, num_nodes=x.size(0))
        row, col = edge_index
        deg = degree(col, x.size(0), dtype=x.dtype).clamp(min=1)
        norm = deg[row].pow(-0.5) * deg[col].pow(-0.5)
        h = self.lin(x)
        msg = h[row] * norm.unsqueeze(-1)
        out = torch.zeros_like(h)
        out.index_add_(0, col, msg)
        return out

class MySAGEConv(nn.Module):
    def __init__(self, in_dim, out_dim):
        super().__init__()
        self.lin_neigh = nn.Linear(in_dim, out_dim, bias=False)  # соседи
        self.lin_self = nn.Linear(in_dim, out_dim, bias=False)  # своя вершина

    def forward(self, x: torch.Tensor, edge_index: torch.Tensor):
        row, col = edge_index  # откуда -> куда
        mask = row != col      # не включаем собственную вершину в среднее соседей
        row, col = row[mask], col[mask]
        agg = torch.zeros_like(x)
        agg.index_add_(0, col, x[row])
        count = x.new_zeros(x.size(0))
        count.index_add_(0, col, x.new_ones(col.numel()))
        agg = agg / count.clamp(min=1).unsqueeze(-1)
        return self.lin_neigh(agg) + self.lin_self(x)